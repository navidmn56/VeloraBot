def get_random_menu_phrase(lang: str = "fa") -> str:
    """دریافت یک عبارت تصادفی کوتاه برای منوی اصلی"""
    if lang == "fa":
        return random.choice(MENU_PHRASES_FA)
    return random.choice(MENU_PHRASES_EN)


def format_start_greeting(user_name: str, lang: str = "fa", rocket_emoji: str = "🚀") -> str:
    """
    قالب‌بندی پیام استارت:
    🚀 سلام {name}! خوش آمدید
    {عبارت داینامیک}
    """
    phrase = get_random_menu_phrase(lang)
    if lang == "fa":
        return f"{rocket_emoji} سلام {user_name}! خوش آمدید\n{phrase}"
    return f"{rocket_emoji} Hello {user_name}! Welcome\n{phrase}"


def format_main_menu_title(lang: str = "fa", rocket_emoji: str = "🚀") -> str:
    """
    قالب‌بندی عنوان منوی اصلی:
    {عبارت داینامیک}
    🚀 منوی اصلی
    """
    phrase = get_random_menu_phrase(lang)
    if lang == "fa":
        return f"{phrase}\n{rocket_emoji} منوی اصلی"
    return f"{phrase}\n{rocket_emoji} Main Menu"
